import React, { useEffect, useState } from 'react';
import {
  Printer,
  X,
  RefreshCw,
  AlertCircle,
  DollarSign,
  Wallet,
  Calendar,
  Download,
  Utensils,
  ShoppingBag,
  Truck,
  Users,
  Receipt,
} from 'lucide-react';
import { DailySummaryResponse } from '../../../functions/api/owner/daily-summary';
import { downloadCsvFile } from '../../utils/csvExport';

interface DailySaleSummaryModalProps {
  isOpen: boolean;
  onClose: () => void;
  initialDate?: string;
}

const getTodayIst = (): string => {
  return new Intl.DateTimeFormat('en-CA', {
    timeZone: 'Asia/Kolkata',
    year: 'numeric',
    month: '2-digit',
    day: '2-digit',
  }).format(new Date());
};

export const DailySaleSummaryModal: React.FC<DailySaleSummaryModalProps> = ({
  isOpen,
  onClose,
  initialDate,
}) => {
  const [selectedDate, setSelectedDate] = useState<string>(initialDate || getTodayIst());
  const [report, setReport] = useState<DailySummaryResponse | null>(null);
  const [loading, setLoading] = useState<boolean>(false);
  const [error, setError] = useState<string | null>(null);

  const fetchDailySummary = async (date: string) => {
    try {
      setLoading(true);
      setError(null);
      const res = await fetch(`/api/owner/daily-summary?date=${encodeURIComponent(date)}`);
      if (!res.ok) {
        const errData = (await res.json().catch(() => ({}))) as { error?: string };
        throw new Error(errData.error || 'Failed to load daily sale summary');
      }
      const data = (await res.json()) as DailySummaryResponse;
      setReport(data);
    } catch (err: any) {
      setError(err.message || 'Error fetching daily sale summary');
    } finally {
      setLoading(false);
    }
  };

  useEffect(() => {
    if (isOpen) {
      fetchDailySummary(selectedDate);
    }
  }, [isOpen, selectedDate]);

  if (!isOpen) return null;

  const handlePrint = () => {
    window.print();
  };

  const handleExportCsv = () => {
    if (!report) return;

    const rows: (string | number | null | undefined)[][] = [
      [`${report.cafe_name.toUpperCase()} - DAILY SALE SUMMARY`],
      ['Date', report.date],
      ['GSTIN', report.gstin || 'N/A'],
      ['Generated At', new Date(report.generated_at).toLocaleString()],
      ['Generated By', report.generated_by],
      [],
      ['--- FINANCIAL SUMMARY ---'],
      ['Total Settled Bills', report.summary.total_bills],
      ['Gross Sales (INR)', report.summary.gross_sales],
      ['Extra Discounts (INR)', report.summary.extra_discounts],
      ['Loyalty Discounts (INR)', report.summary.loyalty_discounts],
      ['Packaging Collected (INR)', report.summary.packaging_collected],
      ['CGST Collected (INR)', report.summary.cgst_collected],
      ['SGST Collected (INR)', report.summary.sgst_collected],
      ['Total Tax / GST Collected (INR)', report.summary.tax_collected],
      ['Net Revenue (INR)', report.summary.net_revenue],
      ['Average Bill Value (INR)', report.summary.avg_bill_value],
      [],
      ['--- PAYMENT DRAWER RECONCILIATION ---'],
      ['Cash Drawer (INR)', report.payment_breakdown.cash_total],
      ['UPI / QR Bank (INR)', report.payment_breakdown.upi_total],
      ['Card POS (INR)', report.payment_breakdown.card_total],
      ['Split Bills Count', report.payment_breakdown.split_bills_count],
      [],
      ['--- DINING CHANNELS ---'],
      ['Channel', 'Bills', 'Revenue (INR)'],
      ['Dine-In', report.dining_breakdown.dine_in.count, report.dining_breakdown.dine_in.revenue],
      ['Takeaway', report.dining_breakdown.takeaway.count, report.dining_breakdown.takeaway.revenue],
      ['Delivery', report.dining_breakdown.delivery.count, report.dining_breakdown.delivery.revenue],
      [],
      ['--- ITEM-WISE DAILY SALES ---'],
      ['Item Name', 'Qty Sold', 'Revenue (INR)'],
      ...report.item_wise_sales.map((it) => [it.item_name, it.quantity_sold, it.total_revenue]),
      [],
      ['--- WAITER-WISE DAILY SALES ---'],
      ['Waiter / Staff Name', 'Bills', 'Revenue (INR)'],
      ...report.waiter_wise_sales.map((w) => [w.waiter_name, w.bills_count, w.net_revenue]),
    ];

    downloadCsvFile(`kimmos-kitchen-daily-summary-${report.date}.csv`, rows);
  };

  return (
    <div className="fixed inset-0 z-50 bg-[#111111]/60 backdrop-blur-xs flex items-center justify-center p-3 sm:p-5 overflow-y-auto">
      <div className="max-w-5xl w-full bg-white border border-[#E6E2DA] rounded-2xl p-5 sm:p-6 shadow-2xl my-auto max-h-[92vh] overflow-y-auto space-y-5">
        {/* MODAL HEADER */}
        <div className="flex flex-col md:flex-row items-stretch md:items-center justify-between gap-3 pb-3 border-b border-[#E6E2DA] no-print">
          <div>
            <div className="flex items-center gap-2">
              <span className="w-2.5 h-2.5 rounded-full bg-[#166534]"></span>
              <h3 className="text-xl font-bold text-[#111111] font-serif">Daily Sale Summary</h3>
            </div>
            <p className="text-xs text-[#52525B] mt-0.5">
              Complete daily sales register, payment drawer totals, item breakdown &amp; thermal/Excel export.
            </p>
          </div>

          <div className="flex items-center gap-2 flex-wrap">
            <div className="flex items-center gap-1.5 bg-[#FAF9F6] border border-[#E6E2DA] rounded-xl px-2.5 py-1.5 text-xs">
              <Calendar className="w-3.5 h-3.5 text-[#52525B]" />
              <input
                type="date"
                value={selectedDate}
                onChange={(e) => setSelectedDate(e.target.value)}
                className="bg-transparent text-xs text-[#111111] font-mono tabular-nums focus:outline-none cursor-pointer"
              />
            </div>

            <button
              type="button"
              onClick={() => fetchDailySummary(selectedDate)}
              disabled={loading}
              title="Refresh daily summary"
              className="p-2 bg-[#F3EFEA] hover:bg-[#E6E2DA] text-[#111111] border border-[#E6E2DA] rounded-xl text-xs transition-colors cursor-pointer"
            >
              <RefreshCw className={`w-3.5 h-3.5 ${loading ? 'animate-spin' : ''}`} />
            </button>

            <button
              type="button"
              onClick={handleExportCsv}
              disabled={!report || loading}
              className="px-3.5 py-2 bg-[#FAF9F6] hover:bg-[#F3EFEA] text-[#111111] border border-[#E6E2DA] rounded-xl text-xs font-bold flex items-center gap-1.5 transition-colors cursor-pointer shadow-2xs whitespace-nowrap disabled:opacity-50"
            >
              <Download className="w-3.5 h-3.5" />
              <span>Download Excel / CSV</span>
            </button>

            <button
              type="button"
              onClick={handlePrint}
              disabled={!report || loading}
              className="px-3.5 py-2 bg-[#111111] hover:bg-[#262626] text-white rounded-xl text-xs font-bold flex items-center gap-1.5 transition-colors cursor-pointer shadow-xs whitespace-nowrap disabled:opacity-50"
            >
              <Printer className="w-3.5 h-3.5" />
              <span>Print 80mm Daily Summary</span>
            </button>

            <button
              type="button"
              onClick={onClose}
              className="text-[#71717A] hover:text-[#111111] p-1.5 rounded-xl hover:bg-[#F3EFEA] transition-colors cursor-pointer"
            >
              <X className="w-5 h-5" />
            </button>
          </div>
        </div>

        {error && (
          <div className="p-3 bg-[#FEF2F2] border border-[#FECACA] rounded-xl text-[#991B1B] text-xs flex items-center justify-between no-print">
            <div className="flex items-center gap-2">
              <AlertCircle className="w-4 h-4 flex-shrink-0" />
              <span className="font-semibold">{error}</span>
            </div>
            <button onClick={() => setError(null)} className="text-[#991B1B] hover:text-[#111111] cursor-pointer">
              &times;
            </button>
          </div>
        )}

        {loading ? (
          <div className="py-16 text-center text-[#71717A] text-xs font-serif no-print">
            Compiling daily sale summary...
          </div>
        ) : !report ? (
          <div className="py-16 text-center text-[#71717A] text-xs italic font-serif no-print">
            No data available for {selectedDate}.
          </div>
        ) : (
          <div className="space-y-5">
            {/* 1. FINANCIAL KPI STRIP */}
            <div className="grid grid-cols-2 lg:grid-cols-4 gap-3 no-print">
              <div className="bg-[#111111] text-white rounded-2xl p-4 shadow-xs">
                <p className="text-[10px] uppercase tracking-wider text-[#E6E2DA] font-bold font-serif">
                  Net Revenue
                </p>
                <p className="text-2xl font-bold font-mono tabular-nums mt-1">
                  ₹{report.summary.net_revenue.toLocaleString('en-IN')}
                </p>
                <p className="text-[11px] text-[#A1A1AA] mt-1 font-serif tabular-nums">
                  Avg Bill: ₹{report.summary.avg_bill_value}
                </p>
              </div>

              <div className="bg-[#FAF9F6] border border-[#E6E2DA] rounded-2xl p-4">
                <div className="flex items-center justify-between text-[#52525B]">
                  <p className="text-[10px] uppercase tracking-wider font-bold font-serif">Total Bills</p>
                  <Receipt className="w-3.5 h-3.5 text-[#111111]" />
                </div>
                <p className="text-2xl font-bold font-mono tabular-nums text-[#111111] mt-1">
                  {report.summary.total_bills}
                </p>
                <p className="text-[11px] text-[#71717A] mt-1 tabular-nums">
                  Gross: ₹{report.summary.gross_sales} &bull; {report.kot_audit.total_kots} KOTs
                </p>
              </div>

              <div className="bg-[#FAF9F6] border border-[#E6E2DA] rounded-2xl p-4">
                <div className="flex items-center justify-between text-[#52525B]">
                  <p className="text-[10px] uppercase tracking-wider font-bold font-serif">GST Collected</p>
                  <DollarSign className="w-3.5 h-3.5 text-[#166534]" />
                </div>
                <p className="text-2xl font-bold font-mono tabular-nums text-[#111111] mt-1">
                  ₹{report.summary.tax_collected}
                </p>
                <p className="text-[11px] text-[#71717A] mt-1 tabular-nums">
                  CGST ₹{report.summary.cgst_collected} + SGST ₹{report.summary.sgst_collected}
                </p>
              </div>

              <div className="bg-[#FAF9F6] border border-[#E6E2DA] rounded-2xl p-4">
                <p className="text-[10px] uppercase tracking-wider text-[#52525B] font-bold font-serif">
                  Discounts &amp; Pkg
                </p>
                <p className="text-xl font-bold font-mono tabular-nums text-[#991B1B] mt-1">
                  -₹{(report.summary.extra_discounts + report.summary.loyalty_discounts).toFixed(2)}
                </p>
                <p className="text-[11px] text-[#52525B] mt-1 tabular-nums">
                  Packaging: +₹{report.summary.packaging_collected}
                </p>
              </div>
            </div>

            {/* 2. DRAWER TOTALS + DINING CHANNELS */}
            <div className="grid grid-cols-1 md:grid-cols-2 gap-4 no-print">
              <div className="bg-[#FAF9F6] border border-[#E6E2DA] rounded-2xl p-4 space-y-3">
                <div className="flex items-center justify-between border-b border-[#E6E2DA] pb-2">
                  <div className="flex items-center gap-2">
                    <Wallet className="w-4 h-4 text-[#111111]" />
                    <span className="font-bold text-xs uppercase tracking-wider font-serif text-[#111111]">
                      Cash / UPI / Card Drawer Totals
                    </span>
                  </div>
                  {report.payment_breakdown.split_bills_count > 0 && (
                    <span className="text-[10px] bg-white border border-[#E6E2DA] px-2 py-0.5 rounded-full font-mono text-[#52525B] tabular-nums">
                      {report.payment_breakdown.split_bills_count} Split Bills
                    </span>
                  )}
                </div>

                <div className="grid grid-cols-3 gap-2 text-center">
                  <div className="bg-white border border-[#E6E2DA] p-2.5 rounded-xl">
                    <p className="text-[10px] text-[#71717A] uppercase font-bold">Cash</p>
                    <p className="text-base font-bold font-mono text-[#111111] tabular-nums mt-0.5">
                      ₹{report.payment_breakdown.cash_total}
                    </p>
                  </div>

                  <div className="bg-white border border-[#E6E2DA] p-2.5 rounded-xl">
                    <p className="text-[10px] text-[#71717A] uppercase font-bold">UPI / QR</p>
                    <p className="text-base font-bold font-mono text-[#166534] tabular-nums mt-0.5">
                      ₹{report.payment_breakdown.upi_total}
                    </p>
                  </div>

                  <div className="bg-white border border-[#E6E2DA] p-2.5 rounded-xl">
                    <p className="text-[10px] text-[#71717A] uppercase font-bold">Card</p>
                    <p className="text-base font-bold font-mono text-[#1D4ED8] tabular-nums mt-0.5">
                      ₹{report.payment_breakdown.card_total}
                    </p>
                  </div>
                </div>
              </div>

              <div className="bg-[#FAF9F6] border border-[#E6E2DA] rounded-2xl p-4 space-y-3">
                <div className="flex items-center gap-2 border-b border-[#E6E2DA] pb-2">
                  <Utensils className="w-4 h-4 text-[#111111]" />
                  <span className="font-bold text-xs uppercase tracking-wider font-serif text-[#111111]">
                    Dining Mode Split
                  </span>
                </div>

                <div className="grid grid-cols-3 gap-2 text-center">
                  <div className="bg-white border border-[#E6E2DA] p-2.5 rounded-xl">
                    <Utensils className="w-3.5 h-3.5 mx-auto text-[#111111] mb-0.5" />
                    <p className="text-[10px] text-[#71717A] font-bold">Dine-In</p>
                    <p className="text-sm font-bold font-mono tabular-nums text-[#111111]">
                      ₹{report.dining_breakdown.dine_in.revenue}
                    </p>
                    <p className="text-[10px] text-[#52525B] tabular-nums">
                      {report.dining_breakdown.dine_in.count} bills
                    </p>
                  </div>

                  <div className="bg-white border border-[#E6E2DA] p-2.5 rounded-xl">
                    <ShoppingBag className="w-3.5 h-3.5 mx-auto text-[#111111] mb-0.5" />
                    <p className="text-[10px] text-[#71717A] font-bold">Takeaway</p>
                    <p className="text-sm font-bold font-mono tabular-nums text-[#111111]">
                      ₹{report.dining_breakdown.takeaway.revenue}
                    </p>
                    <p className="text-[10px] text-[#52525B] tabular-nums">
                      {report.dining_breakdown.takeaway.count} bills
                    </p>
                  </div>

                  <div className="bg-white border border-[#E6E2DA] p-2.5 rounded-xl">
                    <Truck className="w-3.5 h-3.5 mx-auto text-[#111111] mb-0.5" />
                    <p className="text-[10px] text-[#71717A] font-bold">Delivery</p>
                    <p className="text-sm font-bold font-mono tabular-nums text-[#111111]">
                      ₹{report.dining_breakdown.delivery.revenue}
                    </p>
                    <p className="text-[10px] text-[#52525B] tabular-nums">
                      {report.dining_breakdown.delivery.count} bills
                    </p>
                  </div>
                </div>
              </div>
            </div>

            {/* 3. ITEM-WISE & WAITER-WISE SALES TABLES */}
            <div className="grid grid-cols-1 lg:grid-cols-2 gap-4 no-print">
              {/* Item-Wise Sales Table */}
              <div className="bg-white border border-[#E6E2DA] rounded-2xl p-4 space-y-3">
                <div className="flex items-center justify-between border-b border-[#E6E2DA] pb-2">
                  <span className="font-bold text-xs uppercase tracking-wider font-serif text-[#111111]">
                    Item-Wise Daily Sales
                  </span>
                  <span className="text-[10px] text-[#71717A] font-mono tabular-nums">
                    {report.item_wise_sales.length} Items
                  </span>
                </div>

                {report.item_wise_sales.length === 0 ? (
                  <p className="text-xs text-[#71717A] italic py-6 text-center font-serif">
                    No settled items recorded for {report.date}.
                  </p>
                ) : (
                  <div className="max-h-64 overflow-y-auto">
                    <table className="w-full text-left text-xs">
                      <thead className="bg-[#F3EFEA] text-[#52525B] text-[10px] uppercase font-bold sticky top-0">
                        <tr>
                          <th className="px-3 py-2">Item Name</th>
                          <th className="px-3 py-2 text-right">Qty Sold</th>
                          <th className="px-3 py-2 text-right">Revenue (₹)</th>
                        </tr>
                      </thead>
                      <tbody className="divide-y divide-[#E6E2DA]">
                        {report.item_wise_sales.map((item, idx) => (
                          <tr key={idx} className="hover:bg-[#FAF9F6]">
                            <td className="px-3 py-2 font-serif font-semibold text-[#111111]">
                              {item.item_name}
                            </td>
                            <td className="px-3 py-2 text-right font-mono font-bold tabular-nums text-[#111111]">
                              {item.quantity_sold}
                            </td>
                            <td className="px-3 py-2 text-right font-mono font-bold tabular-nums text-[#166534]">
                              ₹{item.total_revenue.toLocaleString('en-IN')}
                            </td>
                          </tr>
                        ))}
                      </tbody>
                    </table>
                  </div>
                )}
              </div>

              {/* Waiter-Wise Sales Table */}
              <div className="bg-white border border-[#E6E2DA] rounded-2xl p-4 space-y-3">
                <div className="flex items-center justify-between border-b border-[#E6E2DA] pb-2">
                  <div className="flex items-center gap-1.5">
                    <Users className="w-4 h-4 text-[#111111]" />
                    <span className="font-bold text-xs uppercase tracking-wider font-serif text-[#111111]">
                      Waiter-Wise Daily Sales
                    </span>
                  </div>
                  <span className="text-[10px] text-[#71717A] font-mono tabular-nums">
                    {report.waiter_wise_sales.length} Staff
                  </span>
                </div>

                {report.waiter_wise_sales.length === 0 ? (
                  <p className="text-xs text-[#71717A] italic py-6 text-center font-serif">
                    No staff sales recorded for {report.date}.
                  </p>
                ) : (
                  <div className="max-h-64 overflow-y-auto">
                    <table className="w-full text-left text-xs">
                      <thead className="bg-[#F3EFEA] text-[#52525B] text-[10px] uppercase font-bold sticky top-0">
                        <tr>
                          <th className="px-3 py-2">Waiter Name</th>
                          <th className="px-3 py-2 text-right">Bills</th>
                          <th className="px-3 py-2 text-right">Revenue (₹)</th>
                        </tr>
                      </thead>
                      <tbody className="divide-y divide-[#E6E2DA]">
                        {report.waiter_wise_sales.map((w, idx) => (
                          <tr key={idx} className="hover:bg-[#FAF9F6]">
                            <td className="px-3 py-2 font-serif font-semibold text-[#111111]">
                              {w.waiter_name}
                            </td>
                            <td className="px-3 py-2 text-right font-mono font-bold tabular-nums text-[#52525B]">
                              {w.bills_count}
                            </td>
                            <td className="px-3 py-2 text-right font-mono font-bold tabular-nums text-[#111111]">
                              ₹{w.net_revenue.toLocaleString('en-IN')}
                            </td>
                          </tr>
                        ))}
                      </tbody>
                    </table>
                  </div>
                )}
              </div>
            </div>

            {/* 4. PRINTABLE 80MM THERMAL DAILY SALE SUMMARY */}
            <div className="pt-2 border-t border-[#E6E2DA] no-print">
              <p className="text-[11px] text-[#52525B] italic text-center mb-2">
                80mm Thermal Print Preview:
              </p>
            </div>

            <div className="printable-receipt bg-[#FAF9F6] border border-[#E6E2DA] rounded-xl p-4 text-xs font-mono space-y-2 text-[#111111]">
              <div className="text-center border-b border-dashed border-[#111111] pb-2">
                <h2 className="text-base font-bold font-serif uppercase tracking-wider">
                  {report.cafe_name}
                </h2>
                <p className="text-[11px] font-bold uppercase mt-0.5">DAILY SALE SUMMARY</p>
                <p className="text-[10px] text-[#52525B]">Business Date: {report.date}</p>
                {report.gstin && (
                  <p className="text-[10px] text-[#52525B]">GSTIN: {report.gstin}</p>
                )}
                <p className="text-[9px] text-[#71717A]">
                  Printed: {new Date(report.generated_at).toLocaleString()}
                </p>
              </div>

              <div className="py-1 border-b border-dashed border-[#111111] space-y-0.5">
                <p className="font-bold text-[11px] uppercase border-b border-[#E6E2DA] pb-0.5">
                  Sales Totals
                </p>
                <div className="flex justify-between">
                  <span>Total Bills:</span>
                  <span className="tabular-nums font-bold">{report.summary.total_bills}</span>
                </div>
                <div className="flex justify-between">
                  <span>Gross Sales:</span>
                  <span className="tabular-nums">₹{report.summary.gross_sales}</span>
                </div>
                {report.summary.extra_discounts > 0 && (
                  <div className="flex justify-between">
                    <span>Extra Discounts:</span>
                    <span className="tabular-nums">-₹{report.summary.extra_discounts}</span>
                  </div>
                )}
                {report.summary.loyalty_discounts > 0 && (
                  <div className="flex justify-between">
                    <span>Loyalty Redeemed:</span>
                    <span className="tabular-nums">-₹{report.summary.loyalty_discounts}</span>
                  </div>
                )}
                {report.summary.packaging_collected > 0 && (
                  <div className="flex justify-between">
                    <span>Packaging:</span>
                    <span className="tabular-nums">+₹{report.summary.packaging_collected}</span>
                  </div>
                )}
                {report.summary.tax_collected > 0 && (
                  <>
                    <div className="flex justify-between">
                      <span>CGST Collected:</span>
                      <span className="tabular-nums">₹{report.summary.cgst_collected}</span>
                    </div>
                    <div className="flex justify-between">
                      <span>SGST Collected:</span>
                      <span className="tabular-nums">₹{report.summary.sgst_collected}</span>
                    </div>
                  </>
                )}
                <div className="flex justify-between font-bold text-sm border-t border-[#111111] pt-0.5">
                  <span>Net Revenue:</span>
                  <span className="tabular-nums">₹{report.summary.net_revenue}</span>
                </div>
              </div>

              <div className="py-1 border-b border-dashed border-[#111111] space-y-0.5">
                <p className="font-bold text-[11px] uppercase border-b border-[#E6E2DA] pb-0.5">
                  Payment Modes
                </p>
                <div className="flex justify-between">
                  <span>Cash:</span>
                  <span className="tabular-nums font-bold">₹{report.payment_breakdown.cash_total}</span>
                </div>
                <div className="flex justify-between">
                  <span>UPI / QR:</span>
                  <span className="tabular-nums font-bold">₹{report.payment_breakdown.upi_total}</span>
                </div>
                <div className="flex justify-between">
                  <span>Card:</span>
                  <span className="tabular-nums font-bold">₹{report.payment_breakdown.card_total}</span>
                </div>
              </div>

              {report.item_wise_sales.length > 0 && (
                <div className="py-1 border-b border-dashed border-[#111111] space-y-0.5 text-[11px]">
                  <p className="font-bold uppercase border-b border-[#E6E2DA] pb-0.5">
                    Item-Wise Sales ({report.item_wise_sales.length})
                  </p>
                  {report.item_wise_sales.map((it, idx) => (
                    <div key={idx} className="flex justify-between gap-2">
                      <span className="truncate">
                        {it.quantity_sold}x {it.item_name}
                      </span>
                      <span className="tabular-nums font-bold">₹{it.total_revenue}</span>
                    </div>
                  ))}
                </div>
              )}

              {report.waiter_wise_sales.length > 0 && (
                <div className="py-1 border-b border-dashed border-[#111111] space-y-0.5 text-[11px]">
                  <p className="font-bold uppercase border-b border-[#E6E2DA] pb-0.5">
                    Staff Breakdown
                  </p>
                  {report.waiter_wise_sales.map((w, idx) => (
                    <div key={idx} className="flex justify-between gap-2">
                      <span className="truncate">
                        {w.waiter_name} ({w.bills_count})
                      </span>
                      <span className="tabular-nums font-bold">₹{w.net_revenue}</span>
                    </div>
                  ))}
                </div>
              )}

              <div className="text-center pt-1 text-[10px] text-[#52525B] italic">
                *** END OF DAILY SALE SUMMARY ***
              </div>
            </div>
          </div>
        )}
      </div>
    </div>
  );
};
